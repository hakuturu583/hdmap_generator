//! A small XML writer for the CommonRoad document.
//!
//! Unlike SUMO's plain files, a CommonRoad document keeps its values as text in
//! elements of their own — `<x>12.5</x>` rather than `x="12.5"` — so this writer
//! has a text leaf besides the empty one. What is borrowed from `quick-xml` is the
//! escaping and the indentation.

use quick_xml::events::{BytesDecl, BytesEnd, BytesStart, BytesText, Event};
use quick_xml::Writer;

/// The document is built in memory, and writing to a `Vec<u8>` has no failure mode
/// to report.
const INFALLIBLE: &str = "writing XML into a string cannot fail";

pub(crate) struct Document {
    writer: Writer<Vec<u8>>,
}

impl Document {
    pub fn new() -> Document {
        let mut writer = Writer::new_with_indent(Vec::new(), b' ', 2);
        writer
            .write_event(Event::Decl(BytesDecl::new("1.0", Some("UTF-8"), None)))
            .expect(INFALLIBLE);
        writer
            .write_event(Event::Comment(BytesText::new(
                " generated by roadgen from the canonical road IR ",
            )))
            .expect(INFALLIBLE);
        Document { writer }
    }

    /// An element with no children.
    pub fn empty(&mut self, name: &str, attributes: &[(&str, String)]) {
        self.writer
            .write_event(Event::Empty(element(name, attributes)))
            .expect(INFALLIBLE);
    }

    /// An element holding nothing but `text`.
    pub fn text(&mut self, name: &str, text: &str) {
        self.writer
            .create_element(name)
            .write_text_content(BytesText::new(text))
            .expect(INFALLIBLE);
    }

    pub fn open(&mut self, name: &str, attributes: &[(&str, String)]) {
        self.writer
            .write_event(Event::Start(element(name, attributes)))
            .expect(INFALLIBLE);
    }

    pub fn close(&mut self, name: &str) {
        self.writer
            .write_event(Event::End(BytesEnd::new(name)))
            .expect(INFALLIBLE);
    }

    pub fn finish(self) -> String {
        let mut xml = String::from_utf8(self.writer.into_inner())
            .expect("quick-xml writes UTF-8 into the buffer it was given");
        xml.push('\n');
        xml
    }
}

fn element<'a>(name: &'a str, attributes: &'a [(&'a str, String)]) -> BytesStart<'a> {
    let mut element = BytesStart::new(name);
    for (key, value) in attributes {
        element.push_attribute((*key, value.as_str()));
    }
    element
}
